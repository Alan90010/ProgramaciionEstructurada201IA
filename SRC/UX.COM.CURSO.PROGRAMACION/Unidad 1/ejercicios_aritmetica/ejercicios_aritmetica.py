# Ejemplo de uso de operadores de aritmetica en Pythob

def mostrar_operadores ():

    # Suma
    suma = 5 + 3
    print("Suma 5 + 3 =", suma)

    # Resta
    resta = 10 - 4
    print("Resta 10 - 4 =", resta)

    # Multiplicacion
    multiplicacion = 6 * 7
    print("Multiplicacion 6 * 7 =", multiplicacion)

    # Division
    division_entera = 10 // 3
    print("Division 10 // 3 =", division_entera)

    # Modulo
    modulo = 10 % 3
    print("Modulo 10 % 3 =", modulo)

    # Potencia
    potencia = 2 ** 3
    print("Potencia 2 ** 3 =", potencia)

def main():
    mostrar_operadores()

if __name__ == "__main__":
    main()